"""ウェイクワードの学習に使う文（合成する言葉）。numpy は要らない。

- `positives(word)`: ウェイクワードの言い方の揺れ（「！」「？」・伸ばす・前に呼びかけ）
- `near_misses(word)`: 聞き間違えやすい近い言葉（1 拍だけ違う・一部だけ・つながった別の語）。
  ウェイクワードはペットごとに違う（pet.json の wakeWord）ので、決め打ちのリストにせず言葉から作る
- `SENTENCES`: 無関係な会話（誤反応を減らす負の例。ウェイクワードに似た音を含むものも混ぜる）
"""

# 拍（モーラ）に分けるときに前の字とくっつく小さい字
_SMALL = set("ゃゅょぁぃぅぇぉゎャュョァィゥェォヮ")

# 1 拍を似た音に置き換える候補。ひらがなだけを扱う
_ROWS = [
    "あいうえお", "かきくけこ", "がぎぐげご", "さしすせそ", "ざじずぜぞ", "たちつてと", "だぢづでど",
    "なにぬねの", "はひふへほ", "ばびぶべぼ", "ぱぴぷぺぽ", "まみむめも", "らりるれろ",
]
# 子音が近い行（同じ母音の位置で入れ替える）
_NEAR_ROWS = ["なにぬねの", "ばびぶべぼ", "まみむめも", "さしすせそ", "たちつてと"]
# 拗音（ちゃ・しゃ…）の頭になる字
_I_COLUMN = "きしちにひみりぎじびぴ"


def morae(word):
    """ひらがな・カタカナの語を拍に分ける（小さい字は前の字に付ける。「ー」「ん」「っ」は 1 拍）。"""
    out = []
    for ch in word:
        if ch in _SMALL and out:
            out[-1] += ch
        else:
            out.append(ch)
    return out


def _similar(mora):
    """1 拍の似た音。直音は母音違い（ま→み・む・め・も）と同じ母音の近い子音（ま→な・ば・さ・た）、
    拗音は頭だけ近い子音に変える（ちゃ→しゃ・きゃ・にゃ…）。"""
    head, tail = mora[0], mora[1:]
    found = []
    if tail:
        if head in _I_COLUMN:
            found = [c for c in _I_COLUMN if c != head]
    else:
        for row in _ROWS:
            if head in row:
                i = row.index(head)
                found = [c for c in row if c != head]
                found += [other[i] for other in _NEAR_ROWS if other != row]
                break
    seen, uniq = set(), []
    for c in found:
        m = c + tail
        if m != mora and m not in seen:
            seen.add(m)
            uniq.append(m)
    return uniq


def near_misses(word, limit=40):
    """ウェイクワードに近いが違う言葉。順番は決まっている（同じ言葉からは同じ並び）。

    1 拍だけ似た音に変えた語、前か後ろを 1 拍落とした語、頭の部分だけ（「まめ」）、
    よくある語尾違い（「くん」「さん」）を並べ、元の語と重複を除く。
    """
    w = word.strip()
    m = morae(w)
    out = []
    if len(m) >= 2:
        for i, mo in enumerate(m):
            for s in _similar(mo)[:4]:
                out.append("".join(m[:i] + [s] + m[i + 1 :]))
        out.append("".join(m[1:]))
        out.append("".join(m[:-1]))
        half = max(1, len(m) // 2)
        out.append("".join(m[:half]))
    if w.endswith("ちゃん"):
        stem = w[: -len("ちゃん")]
        out += [stem + "くん", stem + "さん", stem + "さま", stem, stem + "ちゃう"]
    seen, uniq = {w}, []
    for t in out:
        if t and t not in seen:
            seen.add(t)
            uniq.append(t)
    return uniq[:limit]


def positives(word):
    """ウェイクワードそのものの言い方の揺れ。語の終わりが文の終わりに来るものだけ（検出は語の終わりで判定する）。"""
    w = word.strip()
    m = morae(w)
    # 最後の母音を伸ばす（まめちゃん→まめちゃーん。「ん」「っ」は伸ばせないので 1 つ前の拍）
    k = len(m) - 2 if len(m) >= 2 and m[-1] in ("ん", "っ") else len(m) - 1
    stretched = "".join(m[: k + 1]) + "ー" + "".join(m[k + 1 :])
    return [w, w + "！", w + "？", w + "。", "ねえ、" + w, "ねえ" + w, "あ、" + w, stretched, w + "っ"]


